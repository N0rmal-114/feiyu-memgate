// Assembles the settings page script, client/client.js, from the modules under client/src.
//
// The host loads one script per package (the `./client` export, in the client module system's lazy-CJS
// form), so the modules are joined into it. Nothing is compiled: each .cjs file is placed, indented,
// inside a function of a small registry, and each .css file becomes a module that exports its text.
// The output depends only on the files under client/src (no paths, dates or platform line endings).
//   npm run build-client            rewrite client/client.js when it differs
//   npm run build-client -- --check exit 1 when client/client.js is stale (tests/client-page.test.js checks it too)
// client/README.md describes the layout and the rules for the modules.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SRC_DIR = fileURLToPath(new URL('../client/src/', import.meta.url))
const OUT_FILE = fileURLToPath(new URL('../client/client.js', import.meta.url))

const normalise = (text) => text.replace(/\r\n?/g, '\n')
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0) // code units, the same on every machine

/** Every .cjs and .css file under srcDir as { id, text }, sorted by id; the id is the path under srcDir with '/'. */
export function collect(srcDir = SRC_DIR) {
  const found = []
  const visit = (dir, prefix) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) visit(path.join(dir, entry.name), prefix + entry.name + '/')
      else if (/\.(cjs|css)$/.test(entry.name)) {
        found.push({ id: prefix + entry.name, text: normalise(fs.readFileSync(path.join(dir, entry.name), 'utf8')) })
      }
    }
  }
  visit(srcDir, '')
  return found.sort((a, b) => compare(a.id, b.id))
}

const HEADER = `// Generated by scripts/build-client.mjs from the modules under client/src. Do not edit this file:
// edit the modules and run \`npm run build-client\` (see client/README.md).`

// The registry the modules run in. It is written to be read: define() stores a module body, load() runs
// it once and caches its exports (a module that is required while it is still running gets the exports
// filled so far, as in Node), and each module gets its own require, which resolves './x' and '../x'
// against the module's id and hands every other name to the host's require.
const REGISTRY = `  const bodies = Object.create(null)
  const cache = Object.create(null)
  function define(id, body) {
    bodies[id] = body
  }
  function resolve(from, spec) {
    const parts = from.split('/').slice(0, -1)
    for (const part of spec.split('/')) {
      if (part === '..') parts.pop()
      else if (part !== '.' && part !== '') parts.push(part)
    }
    return parts.join('/')
  }
  function load(id) {
    if (cache[id]) return cache[id].exports
    if (!bodies[id]) throw new Error('dsh-feiyu-memgate: no client module ' + id)
    const module = cache[id] = { exports: {} }
    try {
      bodies[id](requireFrom(id), module, module.exports)
    } catch (error) {
      delete cache[id]
      throw error
    }
    return module.exports
  }
  function requireFrom(from) {
    return (spec) => (spec.startsWith('./') || spec.startsWith('../') ? load(resolve(from, spec)) : hostRequire(spec))
  }`

const indent = (text, pad) => text.split('\n').map((line) => (line ? pad + line : line)).join('\n')

/** The script for a list of { id, text } modules, in the given order. */
export function bundle(modules) {
  const parts = modules.map(({ id, text }) => {
    const body = normalise(text).replace(/\n+$/, '')
    if (id.endsWith('.css')) {
      return `  // ${id}\n  define(${JSON.stringify(id)}, function (require, module) {\n    module.exports = ${JSON.stringify(normalise(text))}\n  })`
    }
    return `  // ${id}\n  define(${JSON.stringify(id)}, function (require, module, exports) {\n${indent(body, '    ')}\n  })`
  })
  const lines = [HEADER, "window.__ModuleLoader__.load({ id: 'dsh-feiyu-memgate', factory: (hostRequire) => {", "  'use strict'", REGISTRY]
  for (const part of parts) lines.push('', part)
  lines.push('', "  return load('index.cjs')", '} })', '')
  return lines.join('\n')
}

/**
 * Assemble client/client.js. With `check` nothing is written.
 * @returns {{ file: string, current: boolean, written: boolean }} current: the file matched before the call
 */
export function build({ check = false, srcDir = SRC_DIR, outFile = OUT_FILE } = {}) {
  const next = bundle(collect(srcDir))
  const previous = fs.existsSync(outFile) ? normalise(fs.readFileSync(outFile, 'utf8')) : null
  const current = previous === next
  if (!check && !current) fs.writeFileSync(outFile, next, 'utf8')
  return { file: outFile, current, written: !check && !current }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const { current, written } = build({ check: process.argv.includes('--check') })
  if (process.argv.includes('--check')) {
    if (!current) {
      console.error('client/client.js is stale; run npm run build-client')
      process.exit(1)
    }
  } else {
    console.log(written ? 'client/client.js: assembled from client/src' : 'client/client.js: already current')
  }
}
